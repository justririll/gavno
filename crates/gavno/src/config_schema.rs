//! Configuration metadata shared verbatim with gavno-settings for offline use.
//! Static data only: no initialization, heap cache, worker or idle callback.
use serde::Serialize;

#[derive(Clone, Copy, Serialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Kind {
    Bool,
    Int { min: i64, max: i64, step: i64 },
    Float { min: f64, max: f64, step: f64 },
    String,
    Color { living: bool },
    Enum { values: &'static [&'static str] },
    StringList,
}
#[derive(Clone, Copy, Serialize)]
#[serde(untagged)]
pub enum Default {
    Bool(bool),
    Int(i64),
    Float(f64),
    String(&'static str),
    Strings(&'static [&'static str]),
    Unset,
}
