/// The modifier default is contextual: nested sessions leave Super to the host.
pub fn json(nested: bool) -> Result<serde_json::Value, String> {
    let mut value = serde_json::to_value(SCHEMA).map_err(|e| e.to_string())?;
    if nested {
        if let Some(keys) = value.as_array_mut() {
            if let Some(key) = keys.iter_mut().find(|key| key["path"] == "mod_key") {
                key["default"] = serde_json::json!("alt");
            }
        }
    }
    Ok(value)
}
